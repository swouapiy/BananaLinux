#!/usr/bin/env python3
# Banana Bistro: bakes the game's sounds (Kenney's Interface Sounds, CC0) into bistro-sounds.h, as 22050 Hz mono
# 16-bit, quiet ends trimmed. Needs soundfile + numpy.
#   bake-sounds.py <Interface Sounds/Audio dir> <out.h>
import sys
import numpy as np, soundfile as sf

SRC, OUT = sys.argv[1:3]
RATE = 22050
SOUNDS = {  # the game's name: the file, its loudness
    "pick": ("pluck_001", 0.8), "drop": ("drop_002", 0.8), "chop": ("tick_002", 0.9), "chopped": ("select_003", 0.7),
    "done": ("glass_002", 0.8), "burnt": ("error_008", 0.8), "served": ("confirmation_002", 0.9),
    "wrong": ("error_004", 0.7), "missed": ("error_006", 0.8), "neworder": ("bong_001", 0.6), "bin": ("close_002", 0.8),
    "dash": ("scratch_002", 0.5), "tick": ("tick_004", 0.9), "move": ("click_001", 0.6), "ok": ("confirmation_001", 0.8),
    "back": ("back_002", 0.7), "switch": ("switch_003", 0.7), "start": ("maximize_006", 0.8), "end": ("minimize_006", 0.8),
}
o = ["// Generated by tools/bake-sounds.py from Kenney's Interface Sounds (CC0). Do not edit.",
     "#pragma once\n#include <cstdint>\nnamespace bistro_sounds {",
     f"constexpr int RATE = {RATE};",
     "struct Clip { const char* name; int n; const int16_t* s; };"]
for name, (f, vol) in SOUNDS.items():
    d, r = sf.read(f"{SRC}/{f}.ogg", dtype="float32", always_2d=True)
    d = d.mean(axis=1)
    n = int(len(d) * RATE / r)
    d = np.interp(np.linspace(0, len(d) - 1, n), np.arange(len(d)), d)
    loud = np.nonzero(np.abs(d) > 0.004)[0]
    if len(loud): d = d[: loud[-1] + 1]
    d = np.clip(d * vol, -1, 1)
    s = (d * 32767).astype(np.int16)
    o.append(f"static const int16_t s_{name}[] = {{" + ",".join(map(str, s.tolist())) + "};")
o.append("static const Clip clips[] = {")
for name in SOUNDS: o.append(f'\t{{ "{name}", (int)(sizeof(s_{name}) / 2), s_{name} }},')
o.append("};\n}")
open(OUT, "w").write("\n".join(o) + "\n")
print(OUT, len(SOUNDS), "sounds")
