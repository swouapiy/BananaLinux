#!/usr/bin/env python3
# Bistro: bakes the CC0 pictures and fonts into bistro-assets.h, so the game is one binary with no image or
# font library. Sprites: Kenney's Food Kit renders (cropped, 64 px and 32 px), plus a few made from them (chopped
# cabbage, the raw patty, burnt things). Fonts: Kenney Future (titles, numbers) and Inter Bold (button letters), as
# Inter SemiBold (sentences), 8-bit coverage at the sizes the game draws.
# Emotes: Kenney's Emotes Pack (CC0), its round bubbles (PNG/Vector/Style 3), over the customers.
#   bake.py <food-kit Previews dir> <Kenney Future.ttf> <Inter-SemiBold.ttf> <Inter-Bold.ttf> <out.h> <emotes Style dir>
import sys
from PIL import Image, ImageFont, ImageDraw

PREV, FUT, SEMI, INTER, OUT, EMO = sys.argv[1:7]

def load(name):
    im = Image.open(f"{PREV}/{name}.png").convert("RGBA")
    return im.crop(im.getbbox())

def tint(im, rgb, amount):
    im = im.copy(); px = im.load()
    for y in range(im.size[1]):
        for x in range(im.size[0]):
            r, g, b, a = px[x, y]
            if a: px[x, y] = (int(r + (rgb[0] - r) * amount), int(g + (rgb[1] - g) * amount), int(b + (rgb[2] - b) * amount), a)
    return im

def pile(im, n=3):
    # a chopped thing: smaller pieces of it, heaped
    s = 64; out = Image.new("RGBA", (s, s)); k = im.copy(); k.thumbnail((36, 36), Image.LANCZOS)
    spots = [(4, 22), (24, 24), (14, 6)][:n]
    for x, y in spots: out.alpha_composite(k, (x, y))
    return out.crop(out.getbbox())

SPRITES = {
    "tomato": load("tomato"), "tomato_cut": load("tomato-slice"),
    "cabbage": load("cabbage"), "cabbage_cut": pile(load("cabbage")),
    "meat": load("meat-raw"), "patty_raw": tint(load("meat-patty"), (214, 92, 92), 0.55),
    "patty": load("meat-patty"), "patty_burnt": tint(load("meat-patty"), (30, 24, 22), 0.75),
    "cheese": load("cheese"), "cheese_cut": load("cheese-cut"),
    "bread": load("bread"),
    "salad": load("salad"), "burger": load("burger-cheese"), "soup": load("bowl-soup"),
    "pot": load("pot"), "pot_soup": load("pot-stew"), "pot_burnt": tint(load("pot-stew"), (30, 24, 22), 0.75),
    "pan": load("frying-pan"), "plate": load("plate"), "bowl": load("bowl"),
    "board": load("cutting-board"), "knife": load("cooking-knife"), "cookie": load("cookie"),
}
for name, f in { "emo_happy": "faceHappy", "emo_sad": "faceSad", "emo_angry": "faceAngry", "emo_hearts": "hearts",
                 "emo_anger": "anger", "emo_dots": "dots3", "emo_heart": "heart" }.items():
    im = Image.open(f"{EMO}/emote_{f}.png").convert("RGBA")
    SPRITES[name] = im.crop(im.getbbox())

def fit(im, s):
    im = im.copy(); r = s / max(im.size)
    return im.resize((max(1, round(im.size[0] * r)), max(1, round(im.size[1] * r))), Image.LANCZOS)

FONTS = [  # name, file, px
    ("future11", FUT, 11), ("future13", FUT, 13), ("future16", FUT, 16), ("future24", FUT, 24), ("future32", FUT, 32),
    ("future48", FUT, 48), ("semi13", SEMI, 13), ("semi15", SEMI, 15), ("inter13", INTER, 13),
]
CHARS = [chr(c) for c in range(32, 127)] + [chr(c) for c in range(0xC0, 0x100)]

o = []
o.append("// Generated by tools/bake.py from Kenney's Food Kit and fonts (CC0) and Inter (OFL). Do not edit.")
o.append("#pragma once\n#include <cstdint>\nnamespace bistro_assets {")
o.append("struct Sprite { const char* name; int w, h; const uint32_t* px; };  // premultiplied 0xAARRGGBB")
names = []
for name, im in SPRITES.items():
    for s in (64, 32):
        f = fit(im, s); w, h = f.size; data = []
        for r, g, b, a in f.get_flattened_data():
            data.append((a << 24) | ((r * a // 255) << 16) | ((g * a // 255) << 8) | (b * a // 255))
        o.append(f"static const uint32_t px_{name}_{s}[] = {{" + ",".join(f"0x{v:x}" for v in data) + "};")
        names.append((f"{name}_{s}", w, h))
o.append("static const Sprite sprites[] = {")
for n, w, h in names: o.append(f'\t{{ "{n}", {w}, {h}, px_{n} }},')
o.append("};")

o.append("struct Glyph { uint32_t cp; int16_t w, h, ox, oy, adv; uint32_t at; };")
o.append("struct Font { const char* name; int px, ascent, descent; int n; const Glyph* g; const uint8_t* bits; };")
for fname, path, px in FONTS:
    ft = ImageFont.truetype(path, px); asc, desc = ft.getmetrics(); bits = []; glyphs = []
    for ch in CHARS:
        if ft.getmask(ch).getbbox() is None and ch != " ":
            # not in this font (an accent Kenney Future lacks): left out, the game draws the plain letter instead
            if ch not in " ": continue
        l, t, r, b = ft.getbbox(ch); adv = round(ft.getlength(ch))
        w, h = max(0, r - l), max(0, b - t)
        img = Image.new("L", (max(1, w), max(1, h))); ImageDraw.Draw(img).text((-l, -t), ch, font=ft, fill=255)
        glyphs.append((ord(ch), w, h, l, t, adv, len(bits)))
        if w and h: bits.extend(img.get_flattened_data())
    o.append(f"static const uint8_t bits_{fname}[] = {{" + ",".join(str(v) for v in bits) + "};")
    o.append(f"static const Glyph glyphs_{fname}[] = {{" + ",".join(f"{{{c},{w},{h},{x},{y},{a},{at}}}" for c, w, h, x, y, a, at in glyphs) + "};")
o.append("static const Font fonts[] = {")
for fname, path, px in FONTS:
    ft = ImageFont.truetype(path, px); asc, desc = ft.getmetrics()
    o.append(f'\t{{ "{fname}", {px}, {asc}, {desc}, (int)(sizeof(glyphs_{fname}) / sizeof(Glyph)), glyphs_{fname}, bits_{fname} }},')
o.append("};\n}")
open(OUT, "w").write("\n".join(o) + "\n")
print(OUT, len(names), "sprites,", len(FONTS), "fonts")
